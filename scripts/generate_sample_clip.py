"""Regenerate the bundled sample clip (maintainer tool; not shipped, not run by CI).

Writes:
    stable/examples/data/sample_clip.mp4
    stable/examples/data/sample_clip.json

Run from anywhere with the repo's dev dependencies installed::

    python scripts/generate_sample_clip.py

Reuses the ``WarpedClipSource`` / ``handheld_transforms`` / ``encode_synthetic_clip``
helpers from ``tests/conftest.py`` (a dev-only import — this script never runs
from an installed package) so the bundled clip is exactly the same kind of
"textured background + known handheld camera path" fixture the Phase 3
acceptance tests already use: a real, decodable H.264+AAC file with genuinely
trackable features and a known ground-truth motion, at a tiny file size. See
``stable/examples/__init__.py`` for how the result is consumed.

Only re-run this if the clip needs to change shape (resolution, duration,
motion) — the checked-in output is what ``stable sample``, the CI headless
integration test, and the README walkthrough all point at, so regenerating it
changes what those exercise.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))
sys.path.insert(0, str(REPO_ROOT / "tests"))

from conftest import WarpedClipSource, encode_synthetic_clip, handheld_transforms  # noqa: E402

OUT_DIR = REPO_ROOT / "stable" / "examples" / "data"

WIDTH, HEIGHT, FPS, FRAMES = 128, 96, 24.0, 120  # exactly 5.0s


def _distance(a: tuple[float, float], b: tuple[float, float]) -> float:
    return ((a[0] - b[0]) ** 2 + (a[1] - b[1]) ** 2) ** 0.5


def main() -> None:
    """Encode the sample clip and write its feature-point metadata alongside it."""
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    transforms = handheld_transforms(
        FRAMES,
        pivot=(WIDTH / 2.0, HEIGHT / 2.0),
        fps=FPS,
        amplitude=4.0,
        rotation=0.015,
        scale=0.008,
        drift_hz=0.35,
        jitter_hz=6.0,
        jitter=0.3,
        seed=5,
    )
    source = WarpedClipSource(transforms, width=WIDTH, height=HEIGHT, fps=FPS, seed=11, n_blobs=10)

    clip_path = OUT_DIR / "sample_clip.mp4"
    encode_synthetic_clip(source, str(clip_path), with_audio=True, crf=28)

    # Greedy farthest-point pick: three well-separated blobs, for a genuine
    # X/Y/R/S RANSAC solve rather than a near-degenerate one.
    blobs = source.feature_points()
    chosen = [blobs[0]]
    for _ in range(2):
        chosen.append(max(blobs, key=lambda p: min(_distance(p, c) for c in chosen)))

    meta = {
        "fps": FPS,
        "width": WIDTH,
        "height": HEIGHT,
        "frames": FRAMES,
        "points": [[round(x, 2), round(y, 2)] for x, y in chosen],
        "description": (
            "Synthetic ~5s handheld-camera clip (textured background, known "
            "similarity motion) used as Stable's bundled sample project and CI's "
            "headless integration test. Generated by scripts/generate_sample_clip.py; "
            "no real footage, no model weights."
        ),
    }
    (OUT_DIR / "sample_clip.json").write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")

    print(f"wrote {clip_path} ({clip_path.stat().st_size} bytes)")
    print(f"wrote {OUT_DIR / 'sample_clip.json'}")
    print("feature points:", chosen)


if __name__ == "__main__":
    main()
